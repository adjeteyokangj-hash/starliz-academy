import { test, expect } from "@playwright/test";
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { codingComponentStyles } from "./coding-styles";
const directory = `artifacts/coding-workbench-uat/preview-size-${randomUUID()}`;
let bundle = "", styles = "";
test.beforeAll(async () => {
  mkdirSync(directory, { recursive: true }); styles = await codingComponentStyles();
  const html = '<main><h1>Fictional creation notes</h1><label for="title">Fictional title</label><input id="title" value="Bridge"><p>Use this private practice page to inspect the same content at different widths.</p></main>';
  const css = 'body{background-color:#ffffff;color:#111111}@media(max-width:400px){body{background-color:#dbeafe}}';
  const built = await build({ stdin: { resolveDir: process.cwd(), loader: "tsx", contents: `import React from'react';import{createRoot}from'react-dom/client';import Preview from'./src/components/coding/ProjectPreview';createRoot(document.getElementById('root')).render(<main className="mx-auto max-w-5xl p-4"><Preview html={${JSON.stringify(html)}} css={${JSON.stringify(css)}} title="Resizable fictional project" resizable/></main>);` }, bundle: true, write: false, platform: "browser", format: "iife", jsx: "automatic", define: { "process.env.NODE_ENV": '"production"' } });
  bundle = built.outputFiles[0]!.text;
});
test("preview sizes change the real iframe viewport and media queries without reloading native inputs", async ({ page }) => {
  await page.route("**/__coding-preview-size", (route) => route.fulfill({ contentType: "text/html", body: `<html><head><style>${styles.replaceAll("</style", "<\\/style")}</style></head><body><div id="root"></div><script>${bundle.replaceAll("</script", "<\\/script")}</script></body></html>` }));
  await page.goto("/__coding-preview-size");
  const frame = page.frameLocator('iframe[title="Resizable fictional project"]'), size = page.getByRole("combobox", { name: "Preview size", exact: true });
  await frame.getByRole("textbox", { name: "Fictional title", exact: true }).fill("Paper bridge");
  await size.selectOption("320");
  await expect.poll(() => frame.locator("body").evaluate(() => innerWidth)).toBe(320);
  await expect(frame.locator("body")).toHaveCSS("background-color", "rgb(219, 234, 254)");
  await size.selectOption("768");
  await expect.poll(() => frame.locator("body").evaluate(() => innerWidth)).toBe(768);
  await expect(frame.locator("body")).toHaveCSS("background-color", "rgb(255, 255, 255)");
  await expect(frame.getByRole("textbox", { name: "Fictional title", exact: true })).toHaveValue("Paper bridge");
  await page.setViewportSize({ width: 390, height: 1000 });
  await size.selectOption("1024");
  await expect.poll(() => frame.locator("body").evaluate(() => innerWidth)).toBe(1024);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const scroller = page.getByRole("region", { name: "Scrollable project preview", exact: true });
  await scroller.focus(); await page.keyboard.press("ArrowRight");
  await expect.poll(() => scroller.evaluate((element) => element.scrollLeft)).toBeGreaterThan(0);
  await size.selectOption("fit");
  expect(await frame.locator("body").evaluate(() => innerWidth)).toBeLessThan(390);
  await expect(frame.getByRole("textbox", { name: "Fictional title", exact: true })).toHaveValue("Paper bridge");
  await page.screenshot({ path: `${directory}/390.png`, fullPage: true });
  writeFileSync(`${directory}/result.json`, JSON.stringify({ passed: true, realBrowserViewports: [320, 768, 1024], actualMediaQueryEvaluation: true, nativeInputRetainedAcrossResize: true, keyboardHorizontalScroll: true, mobileHostOverflow: false, serverCssLayoutAssessmentClaim: false, learnerJavascriptExecutedInPreview: false }, null, 2), { flag: "wx" });
});
